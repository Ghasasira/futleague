/**
 * Computes the official 10-match performance timeline for any club,
 * dynamically merging any real-time finished or live matches from the active league.
 */
export function getTeamPerformanceTrend(
  teamId: string,
  allTeams: Team[],
  allMatches: Match[] = []
): TeamMomentumSummary {
  // Grab base logs or fallback to generic
  const baseLogs = BASE_TEAM_LOGS[teamId] || BASE_TEAM_LOGS['apex-city'];
  
  // Clone base logs
  const matchesMap = new Map<number, Omit<TeamPerformanceMatch, 'cumulativePoints'>>();
  baseLogs.forEach((m) => {
    matchesMap.set(m.matchweek, { ...m });
  });

  // Check if any actual recorded finished matches exist for this team in allMatches
  const finishedOrLiveMatches = allMatches.filter(
    (m) =>
      (m.homeTeamId === teamId || m.awayTeamId === teamId) &&
      (m.status === 'FINISHED' || m.status === 'LIVE')
  );

  finishedOrLiveMatches.forEach((actualMatch) => {
    const isHome = actualMatch.homeTeamId === teamId;
    const teamScore = isHome ? actualMatch.homeScore : actualMatch.awayScore;
    const opponentScore = isHome ? actualMatch.awayScore : actualMatch.homeScore;
    const opponentTeamId = isHome ? actualMatch.awayTeamId : actualMatch.homeTeamId;
    const opponentTeam = allTeams.find((t) => t.id === opponentTeamId);

    const result: 'W' | 'D' | 'L' =
      teamScore > opponentScore ? 'W' : teamScore === opponentScore ? 'D' : 'L';
    const points = result === 'W' ? 3 : result === 'D' ? 1 : 0;

    const teamXG = isHome ? actualMatch.stats.xG[0] : actualMatch.stats.xG[1];
    const opponentXG = isHome ? actualMatch.stats.xG[1] : actualMatch.stats.xG[0];
    const possession = isHome ? actualMatch.stats.possession[0] : actualMatch.stats.possession[1];

    // Compute synthetic rating from score and stats
    const ratingBase = 7.0 + (teamScore - opponentScore) * 0.7 + (teamXG - opponentXG) * 0.4;
    const clampedRating = Math.min(9.8, Math.max(5.5, Number(ratingBase.toFixed(1))));

    matchesMap.set(actualMatch.matchweek, {
      matchId: actualMatch.id,
      matchweek: actualMatch.matchweek,
      date: actualMatch.date,
      opponentId: opponentTeamId,
      opponentName: opponentTeam?.name || 'Opponent',
      opponentShortName: opponentTeam?.shortName || 'Opp',
      isHome,
      teamScore,
      opponentScore,
      result,
      points,
      rating: clampedRating,
      teamXG,
      opponentXG,
      possession,
      venue: actualMatch.venue,
      goalDiff: teamScore - opponentScore,
      keyMoment:
        actualMatch.events.length > 0
          ? `${actualMatch.events[actualMatch.events.length - 1].minute}' ${actualMatch.events[actualMatch.events.length - 1].detail || actualMatch.events[actualMatch.events.length - 1].type}`
          : undefined,
    });
  });

  // Convert to sorted array and take the latest 10 matches
  const sortedMatches = Array.from(matchesMap.values()).sort(
    (a, b) => a.matchweek - b.matchweek
  );
  const last10 = sortedMatches.slice(-10);

  // Calculate cumulative points over the 10 games
  let rollingPoints = 0;
  const matchesWithCumulative: TeamPerformanceMatch[] = last10.map((m) => {
    rollingPoints += m.points;
    return {
      ...m,
      cumulativePoints: rollingPoints,
    };
  });

  // Aggregate totals
  const totalPoints = rollingPoints;
  const wins = matchesWithCumulative.filter((m) => m.result === 'W').length;
  const draws = matchesWithCumulative.filter((m) => m.result === 'D').length;
  const losses = matchesWithCumulative.filter((m) => m.result === 'L').length;
  const goalsScored = matchesWithCumulative.reduce((sum, m) => sum + m.teamScore, 0);
  const goalsConceded = matchesWithCumulative.reduce((sum, m) => sum + m.opponentScore, 0);
  const goalDifference = goalsScored - goalsConceded;
  const cleanSheets = matchesWithCumulative.filter((m) => m.opponentScore === 0).length;
  const averageRating = Number(
    (matchesWithCumulative.reduce((sum, m) => sum + m.rating, 0) / matchesWithCumulative.length).toFixed(2)
  );
  const averageXG = Number(
    (matchesWithCumulative.reduce((sum, m) => sum + m.teamXG, 0) / matchesWithCumulative.length).toFixed(2)
  );
  const averagePossession = Math.round(
    matchesWithCumulative.reduce((sum, m) => sum + m.possession, 0) / matchesWithCumulative.length
  );

  // Momentum scoring calculation (0 to 100):
  // Points weight (50%), Recent 3 games weighting (25%), Goal Diff (15%), xG Dominance (10%)
  const recent3 = matchesWithCumulative.slice(-3);
  const recent3Points = recent3.reduce((sum, m) => sum + m.points, 0); // max 9
  const pointsScore = (totalPoints / 30) * 50;
  const recentFormScore = (recent3Points / 9) * 25;
  const gdScore = Math.min(15, Math.max(0, (goalDifference + 10) * 0.75));
  const xGDiff = averageXG - (goalsConceded / 10);
  const xGScore = Math.min(10, Math.max(0, (xGDiff + 1.5) * 3.3));

  const momentumScore = Math.min(100, Math.max(10, Math.round(pointsScore + recentFormScore + gdScore + xGScore)));

  let momentumStatus: TeamMomentumSummary['momentumStatus'] = 'STABLE';
  let momentumLabel = 'Stable Rhythm';

  if (momentumScore >= 82) {
    momentumStatus = 'SURGING';
    momentumLabel = 'Surging Momentum 🔥';
  } else if (momentumScore >= 68) {
    momentumStatus = 'POSITIVE';
    momentumLabel = 'Ascending Momentum ⚡';
  } else if (momentumScore >= 45) {
    momentumStatus = 'STABLE';
    momentumLabel = 'Consistent Pace ⚖️';
  } else if (momentumScore >= 30) {
    momentumStatus = 'COOLING';
    momentumLabel = 'Cooling Off ⚠️';
  } else {
    momentumStatus = 'STRUGGLING';
    momentumLabel = 'Critical Slump 🚨';
  }

  // Calculate streak from latest matches backwards
  let streakCount = 0;
  const latestResult = matchesWithCumulative[matchesWithCumulative.length - 1]?.result;
  for (let i = matchesWithCumulative.length - 1; i >= 0; i--) {
    if (matchesWithCumulative[i].result === latestResult) {
      streakCount++;
    } else {
      break;
    }
  }

  const streakType =
    latestResult === 'W' ? 'Win' : latestResult === 'D' ? 'Draw' : 'Loss';
  const currentStreak =
    streakCount > 1
      ? `${streakCount}-Match ${streakType} Streak`
      : `Last: ${streakType}`;

  return {
    teamId,
    matches: matchesWithCumulative,
    totalPoints,
    wins,
    draws,
    losses,
    goalsScored,
    goalsConceded,
    goalDifference,
    cleanSheets,
    averageRating,
    averageXG,
    averagePossession,
    momentumScore,
    momentumStatus,
    momentumLabel,
    pointsPercentage: Math.round((totalPoints / 30) * 100),
    currentStreak,
  };
}
